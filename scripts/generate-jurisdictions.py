"""Generate the bundled US state/county list from the 2026 Census Gazetteer."""
import csv
import io
import json
from pathlib import Path
from urllib.request import urlopen
from zipfile import ZipFile

SOURCE = "https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2026_Gazetteer/"


def records(kind):
    with urlopen(f"{SOURCE}2026_Gaz_{kind}_national.zip") as response:
        with ZipFile(io.BytesIO(response.read())) as archive:
            content = archive.read(archive.namelist()[0]).decode("utf-8-sig")
    return list(csv.DictReader(io.StringIO(content), delimiter="|"))


states = {row["USPS"]: row["NAME"] for row in records("state") if row["USPS"] not in {"DC", "PR"}}
jurisdictions = {name: [] for name in sorted(states.values())}
for row in records("counties"):
    if row["USPS"] in states:
        jurisdictions[states[row["USPS"]]].append(row["NAME"])
for counties in jurisdictions.values():
    counties.sort()
assert len(jurisdictions) == 50
target = Path(__file__).resolve().parents[1] / "src/features/choices/config/jurisdictions.ts"
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(
    "// Generated by scripts/generate-jurisdictions.py from the 2026 Census Gazetteer.\n"
    f"// Source: {SOURCE}\n"
    "export const JURISDICTIONS: Readonly<Record<string, readonly string[]>> = "
    + json.dumps(jurisdictions, ensure_ascii=False, indent=2) + ";\n",
    encoding="utf-8",
)
print(f"Generated {len(jurisdictions)} states and {sum(map(len, jurisdictions.values()))} jurisdictions.")
